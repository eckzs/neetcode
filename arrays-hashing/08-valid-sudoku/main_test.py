import unittest

from main import Solution


class TestValidSudoku(unittest.TestCase):
    def test_example_1_valid(self):
        board = [["1","2",".",".","3",".",".",".","."],
                ["4",".",".","5",".",".",".",".","."],
                [".","9","8",".",".",".",".",".","3"],
                ["5",".",".",".","6",".",".",".","4"],
                [".",".",".","8",".","3",".",".","5"],
                ["7",".",".",".","2",".",".",".","6"],
                [".",".",".",".",".",".","2",".","."],
                [".",".",".","4","1","9",".",".","8"],
                [".",".",".",".","8",".",".","7","9"]]
        self.assertTrue(Solution().isValidSudoku(board))

    def test_example_2_invalid(self):
        board = [["1","2",".",".","3",".",".",".","."],
                ["4",".",".","5",".",".",".",".","."],
                [".","9","1",".",".",".",".",".","3"],
                ["5",".",".",".","6",".",".",".","4"],
                [".",".",".","8",".","3",".",".","5"],
                ["7",".",".",".","2",".",".",".","6"],
                [".",".",".",".",".",".","2",".","."],
                [".",".",".","4","1","9",".",".","8"],
                [".",".",".",".","8",".",".","7","9"]]
        self.assertFalse(Solution().isValidSudoku(board))


if __name__ == "__main__":
    unittest.main()
